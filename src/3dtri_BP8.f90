!===============================================================================
! Gathers the full state to master, computes derived fields (shear stress,
! pore pressure, Darcy velocity, log10 slip-rate/state), and writes one
! time-step's worth of data to every open output file. Called at each
! scheduled output time (see the tint_out trigger in the main program).
!===============================================================================
subroutine write_all_output(myid, t, yt, dydt, local_cells, Nt_all, sendcounts, displs)
  use mpi
  use bp8_module
  implicit none
  integer, intent(in) :: myid, local_cells, Nt_all
  real(DP), intent(in) :: t, yt(3*local_cells), dydt(3*local_cells)
  integer, intent(in) :: sendcounts(0:*), displs(0:*)

  real(DP), allocatable :: s2l(:), s3l(:), thl(:)
  real(DP), allocatable :: s2a(:), s3a(:), V2a(:), V3a(:), tha(:)
  real(DP), allocatable :: tau2a(:), tau3a(:), pa(:), dpdta(:), q2a(:), q3a(:)
  integer :: i, k, ierr
  real(DP) :: Vmax, moment_rate, Vmag
  real(DP) :: half, dz, gmax_resid
  integer :: gmax_iter

  allocate(s2l(local_cells), s3l(local_cells), thl(local_cells))
  do i = 1, local_cells
    s2l(i) = yt(3*i-2); s3l(i) = yt(3*i-1); thl(i) = yt(3*i)
  end do

  if (myid == 0) then
    allocate(s2a(Nt_all), s3a(Nt_all), V2a(Nt_all), V3a(Nt_all), tha(Nt_all))
    allocate(tau2a(Nt_all), tau3a(Nt_all), pa(Nt_all), dpdta(Nt_all), q2a(Nt_all), q3a(Nt_all))
  else
    allocate(s2a(1), s3a(1), V2a(1), V3a(1), tha(1))
    allocate(tau2a(1), tau3a(1), pa(1), dpdta(1), q2a(1), q3a(1))
  end if

  ! Slip rate and traction come straight from derivs()'s force-balance
  ! solve (module arrays Vsol*/tausol*), which the main loop has just
  ! evaluated at this accepted state -- no need to reconstruct the
  ! friction law here, and no possibility of the output disagreeing with
  ! what the solver actually used.
  call MPI_Gatherv(s2l, local_cells, MPI_Real8, s2a, sendcounts, displs, MPI_Real8, 0, MPI_COMM_WORLD, ierr)
  call MPI_Gatherv(s3l, local_cells, MPI_Real8, s3a, sendcounts, displs, MPI_Real8, 0, MPI_COMM_WORLD, ierr)
  call MPI_Gatherv(thl, local_cells, MPI_Real8, tha, sendcounts, displs, MPI_Real8, 0, MPI_COMM_WORLD, ierr)
  call MPI_Gatherv(Vsol2, local_cells, MPI_Real8, V2a, sendcounts, displs, MPI_Real8, 0, MPI_COMM_WORLD, ierr)
  call MPI_Gatherv(Vsol3, local_cells, MPI_Real8, V3a, sendcounts, displs, MPI_Real8, 0, MPI_COMM_WORLD, ierr)
  call MPI_Gatherv(tausol2, local_cells, MPI_Real8, tau2a, sendcounts, displs, MPI_Real8, 0, MPI_COMM_WORLD, ierr)
  call MPI_Gatherv(tausol3, local_cells, MPI_Real8, tau3a, sendcounts, displs, MPI_Real8, 0, MPI_COMM_WORLD, ierr)

  ! Monitor the force-balance solve: this replaces the drift check the
  ! derivative formulation needed, and should stay at round-off.
  call MPI_Reduce(newton_max_resid, gmax_resid, 1, MPI_Real8, MPI_MAX, 0, MPI_COMM_WORLD, ierr)
  call MPI_Reduce(newton_max_iter, gmax_iter, 1, MPI_INTEGER, MPI_MAX, 0, MPI_COMM_WORLD, ierr)
  newton_max_resid = 0.0_DP
  newton_max_iter = 0

  if (myid /= 0) then
    deallocate(s2l, s3l, thl)
    deallocate(s2a, s3a, V2a, V3a, tha, tau2a, tau3a, pa, dpdta, q2a, q3a)
    return
  end if

  if (gmax_resid > 1.0d-8) then
    write(*,'(A,E12.4,A,I4,A,E14.6)') ' WARNING: force-balance residual ', gmax_resid, &
        ' (max Newton iters ', gmax_iter, ') at t=', t
  end if

  half = lf_half
  dz = dz_cell

  do k = 1, Nt_all
    call pf_lookup(t, k, pa(k), dpdta(k))

    ! Darcy velocity via central finite difference of the pressure history
    ! at neighboring elements (Eq. 16): q_j = -(k/eta)*dp/dx_j, and
    ! k/eta = alpha*beta*phi (since alpha=k/(phi*beta*eta)).
    call darcy_component(t, k, 2, q2a(k))
    call darcy_component(t, k, 3, q3a(k))
  end do

  ! Locked elements are physically V=0, so they contribute nothing here.
  Vmax = 0.0_DP
  moment_rate = 0.0_DP
  do k = 1, Nt_all
    if (abs(cx2_all(k)) >= lf_fixed .or. abs(cx3_all(k)) >= lf_fixed) cycle
    Vmag = sqrt(V2a(k)**2 + V3a(k)**2)
    Vmax = max(Vmax, Vmag)
    moment_rate = moment_rate + xmu * Vmag * (0.5_DP * dz**2)
  end do

  ! --- station files ---
  block
    real(DP) :: stx2(9), stx3(9)
    integer :: is2
    stx2 = [0.0_DP, -200.0_DP, 0.0_DP, 200.0_DP, 0.0_DP, -200.0_DP, -200.0_DP, 200.0_DP, 200.0_DP]
    stx3 = [0.0_DP, 0.0_DP, 200.0_DP, 0.0_DP, -200.0_DP, -200.0_DP, 200.0_DP, -200.0_DP, 200.0_DP]
    do is2 = 1, 9
      call write_station_row(300+is2, t, stx2(is2), stx3(is2), n_side, dz, half, &
          s2a, s3a, V2a, V3a, tau2a, tau3a, pa, q2a, q3a, tha, Nt_all)
    end do
  end block

  ! --- global.dat ---
  write(400,'(3E15.7)') t, log10(max(Vmax,1.0d-20)), moment_rate

  ! --- profile files (strike: x3=0 line; depth: x2=0 line) ---
  call write_profile_row(410, t, Vmax, 'x2', s2a,   n_side, dz, half, Nt_all)
  call write_profile_row(411, t, Vmax, 'x3', s2a,   n_side, dz, half, Nt_all)
  call write_profile_row(412, t, Vmax, 'x2', s3a,   n_side, dz, half, Nt_all)
  call write_profile_row(413, t, Vmax, 'x3', s3a,   n_side, dz, half, Nt_all)
  call write_profile_row(414, t, Vmax, 'x2', tau2a, n_side, dz, half, Nt_all)
  call write_profile_row(415, t, Vmax, 'x3', tau2a, n_side, dz, half, Nt_all)
  call write_profile_row(416, t, Vmax, 'x2', tau3a, n_side, dz, half, Nt_all)
  call write_profile_row(417, t, Vmax, 'x3', tau3a, n_side, dz, half, Nt_all)
  call write_profile_row(418, t, Vmax, 'x2', pa,    n_side, dz, half, Nt_all)
  call write_profile_row(419, t, Vmax, 'x3', pa,    n_side, dz, half, Nt_all)

  ! Flush every output file after each step: this is a multi-day run with
  ! no checkpointing, so an interrupted/killed/preempted job should not
  ! lose output that the code already "wrote" but the OS never persisted.
  ! (Small files like global.dat can otherwise sit at 0 bytes for hours --
  ! confirmed during testing: killing an in-progress run left it empty
  ! even though station/profile files, which cross the buffer threshold
  ! sooner due to higher per-step byte volume, already showed data.)
  block
    integer :: fu
    do fu = 301, 309
      flush(fu)
    end do
    flush(400)
    do fu = 410, 419
      flush(fu)
    end do
  end block

  deallocate(s2l, s3l, thl)
  deallocate(s2a, s3a, V2a, V3a, tha, tau2a, tau3a, pa, dpdta, q2a, q3a)

end subroutine write_all_output


subroutine darcy_component(t, k, comp, qval)
  use bp8_module
  implicit none
  real(DP), intent(in) :: t
  integer, intent(in) :: k, comp
  real(DP), intent(out) :: qval
  integer :: i0, j0, i1, j1, k1a, k2a, k1b, k2b
  real(DP) :: p_a, p_b, dpdt_dummy, k_over_eta

  call k_to_ij(k, n_side, i0, j0)
  k_over_eta = alpha_diff * beta_diff * phi_diff

  if (comp == 2) then
    i1 = max(0, i0 - 1)
    call ij_to_k(min(n_side-1,i0+1), j0, n_side, k1a, k2a)
    call ij_to_k(i1, j0, n_side, k1b, k2b)
  else
    j1 = max(0, j0 - 1)
    call ij_to_k(i0, min(n_side-1,j0+1), n_side, k1a, k2a)
    call ij_to_k(i0, j1, n_side, k1b, k2b)
  end if

  call pf_lookup(t, k1a, p_a, dpdt_dummy)
  call pf_lookup(t, k1b, p_b, dpdt_dummy)
  ! call again with the second triangle of each neighboring cell and average
  block
    real(DP) :: p_a2, p_b2
    call pf_lookup(t, k2a, p_a2, dpdt_dummy)
    call pf_lookup(t, k2b, p_b2, dpdt_dummy)
    p_a = 0.5_DP * (p_a + p_a2)
    p_b = 0.5_DP * (p_b + p_b2)
  end block

  qval = -k_over_eta * (p_a - p_b) / (2.0_DP * dz_cell)
end subroutine darcy_component


subroutine write_station_row(unit_no, t, x2q, x3q, n_side, dz, half, &
    s2a, s3a, V2a, V3a, tau2a, tau3a, pa, q2a, q3a, tha, Nt_all)
  use bp8_module, only: DP
  implicit none
  integer, intent(in) :: unit_no, n_side, Nt_all
  real(DP), intent(in) :: t, x2q, x3q, dz, half
  real(DP), intent(in) :: s2a(Nt_all), s3a(Nt_all), V2a(Nt_all), V3a(Nt_all)
  real(DP), intent(in) :: tau2a(Nt_all), tau3a(Nt_all), pa(Nt_all), q2a(Nt_all), q3a(Nt_all)
  real(DP), intent(in) :: tha(Nt_all)
  real(DP) :: s2v, s3v, V2v, V3v, tau2v, tau3v, pv, q2v, q3v, thv
  real(DP) :: cellf(n_side, n_side)
  real(DP) :: bilinear_cell
  external :: bilinear_cell

  call build_cell_field(s2a, Nt_all, n_side, cellf); s2v = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(s3a, Nt_all, n_side, cellf); s3v = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(V2a, Nt_all, n_side, cellf); V2v = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(V3a, Nt_all, n_side, cellf); V3v = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(tau2a, Nt_all, n_side, cellf); tau2v = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(tau3a, Nt_all, n_side, cellf); tau3v = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(pa, Nt_all, n_side, cellf); pv = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(q2a, Nt_all, n_side, cellf); q2v = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(q3a, Nt_all, n_side, cellf); q3v = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)
  call build_cell_field(tha, Nt_all, n_side, cellf); thv = bilinear_cell(cellf, n_side, dz, half, x2q, x3q)

  write(unit_no,'(E22.14,10E15.7)') t, s2v, s3v, &
      log10(max(abs(V2v),1.0d-20)), log10(max(abs(V3v),1.0d-20)), &
      tau2v/1.0d6, tau3v/1.0d6, pv/1.0d6, q2v, q3v, log10(max(thv,1.0d-20))
end subroutine write_station_row


! Query points are the FIXED BP8-required grid (-lf_fixed to lf_fixed at
! node_dz_fixed=10m, n_nodes_fixed=81 nodes; see bp8_module.f90) regardless
! of the mesh's own resolution/domain size. n_side/dz/half here describe
! the MESH's own (interpolation-source) grid, passed through to
! build_cell_field/bilinear_cell -- a coarser or larger mesh just means
! the same fixed query points get interpolated from a coarser or
! differently-sized source grid.
subroutine write_profile_row(unit_no, t, Vmax, axis, field, n_side, dz, half, Nt_all)
  use bp8_module, only: DP, lf_fixed, n_nodes_fixed, node_dz_fixed
  implicit none
  integer, intent(in) :: unit_no, n_side, Nt_all
  real(DP), intent(in) :: t, Vmax, dz, half
  character(len=2), intent(in) :: axis
  real(DP), intent(in) :: field(Nt_all)
  integer :: i
  real(DP) :: row(n_nodes_fixed)
  real(DP) :: node, cellf(n_side, n_side)
  real(DP) :: bilinear_cell
  external :: bilinear_cell
  character(len=32) :: fmt_str

  call build_cell_field(field, Nt_all, n_side, cellf)

  do i = 1, n_nodes_fixed
    node = -lf_fixed + real(i-1, DP) * node_dz_fixed
    if (axis == 'x2') then
      row(i) = bilinear_cell(cellf, n_side, dz, half, node, 0.0_DP)
    else
      row(i) = bilinear_cell(cellf, n_side, dz, half, 0.0_DP, node)
    end if
  end do

  write(fmt_str,'(A,I0,A)') '(2E22.14,', n_nodes_fixed, 'E15.7)'
  write(unit_no,fmt_str) t, log10(max(Vmax,1.0d-20)), row
end subroutine write_profile_row
